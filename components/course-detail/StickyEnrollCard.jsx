"use client";

import { Check, ShieldCheck, Download, Sparkles, Clock, Calendar, Users, Award } from "lucide-react";
import Button from "../ui/Button";

export default function StickyEnrollCard({ course, onOpenEnrollModal }) {
  const savings = course.originalPrice - course.price;
  const discountPercent = Math.round((savings / course.originalPrice) * 100);

  // Reliable client-side syllabus overview download generator
  const handleDownloadSyllabus = () => {
    const syllabusContent = `
=====================================================
RAIVATEDU COHORT SYLLABUS OVERVIEW (SAMPLE CURRICULUM)
=====================================================
Program: ${course.title}
Discipline: ${course.categoryName}
Level: ${course.level}
Duration: ${course.durationWeeks} Weeks (${course.hoursPerWeek} hrs/week)
Next Cohort Date: ${course.nextCohortDate}
Tuition: INR ${course.price.toLocaleString("en-IN")} (Original: INR ${course.originalPrice.toLocaleString("en-IN")})

PROGRAM OUTCOMES:
${course.outcomes.map((o, idx) => `  ${idx + 1}. ${o}`).join("\n")}

CURRICULUM MODULES:
${course.syllabus
  .map(
    (m, idx) => `
Module ${idx + 1}: ${m.title} (${m.week})
- Lessons: ${m.lessonsCount}
- Topics: ${m.topics.join(", ")}
- Milestone Deliverable: ${m.project}
`
  )
  .join("\n")}

MENTOR:
Name: ${course.mentor?.name} (${course.mentor?.title})
Bio: ${course.mentor?.bio}

NOTICE:
This is an illustrative curriculum document generated by the Raivatedu
frontend internship prototype for Meru Technosoft Private Limited.
=====================================================
`.trim();

    const blob = new Blob([syllabusContent], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `${course.slug}-syllabus-overview.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const inclusions = [
    `${course.durationWeeks} Weeks Structured Cohort Milestones`,
    `${course.projectsCount || 4} Production-Grade Capstones`,
    "Bi-weekly 1:1 Practitioner Code Reviews",
    "Verified Certificate of Completion",
    "Lifetime Access to Alumni & Discord Community",
    "Career Architecture & Portfolio Polish",
  ];

  return (
    <div className="bg-white rounded-3xl p-6 sm:p-8 border border-[#E7E0D6] shadow-xl shadow-indigo-950/5 relative">
      {/* Top Batch Alert Tag */}
      <div className="flex items-center justify-between gap-2 pb-4 mb-5 border-b border-[#E7E0D6]">
        <div className="flex items-center gap-1.5">
          <span className="w-2.5 h-2.5 rounded-full bg-emerald-500 animate-pulse" />
          <span className="text-xs font-bold uppercase tracking-wider text-[#1E1B4B]">
            Cohort Enrolling
          </span>
        </div>
        <span className="text-[11px] font-bold px-2.5 py-0.5 rounded-full bg-[#FEF3C7] text-[#92400E] border border-[#FDE68A]">
          Few Seats Left
        </span>
      </div>

      {/* Pricing Header */}
      <div className="mb-6">
        <div className="flex items-baseline gap-2">
          <span className="text-3xl sm:text-4xl font-black text-[#1E1B4B]">
            ₹{course.price.toLocaleString("en-IN")}
          </span>
          <span className="text-sm text-[#94A3B8] line-through font-medium">
            ₹{course.originalPrice.toLocaleString("en-IN")}
          </span>
        </div>
        <div className="mt-1 flex items-center gap-2">
          <span className="text-xs font-bold text-emerald-700 bg-emerald-50 px-2.5 py-0.5 rounded-md border border-emerald-200">
            Save ₹{savings.toLocaleString("en-IN")} ({discountPercent}% Off)
          </span>
          <span className="text-xs text-[#64748B]">Inclusive of all taxes</span>
        </div>
      </div>

      {/* Meta Specifications */}
      <div className="space-y-2.5 py-4 border-y border-[#E7E0D6] text-xs font-medium text-[#334155] mb-6">
        <div className="flex items-center justify-between">
          <span className="flex items-center gap-1.5 text-[#64748B]">
            <Calendar className="w-4 h-4 text-[#4338CA]" aria-hidden="true" />
            <span>Next Cohort Date:</span>
          </span>
          <span className="font-bold text-[#1E1B4B]">{course.nextCohortDate}</span>
        </div>
        <div className="flex items-center justify-between">
          <span className="flex items-center gap-1.5 text-[#64748B]">
            <Clock className="w-4 h-4 text-[#4338CA]" aria-hidden="true" />
            <span>Duration:</span>
          </span>
          <span className="font-bold text-[#1E1B4B]">{course.durationWeeks} Weeks ({course.hoursPerWeek} hrs/wk)</span>
        </div>
        <div className="flex items-center justify-between">
          <span className="flex items-center gap-1.5 text-[#64748B]">
            <Users className="w-4 h-4 text-[#4338CA]" aria-hidden="true" />
            <span>Cohort Size:</span>
          </span>
          <span className="font-bold text-[#1E1B4B]">Max 25 Learners</span>
        </div>
        <div className="flex items-center justify-between">
          <span className="flex items-center gap-1.5 text-[#64748B]">
            <Award className="w-4 h-4 text-[#4338CA]" aria-hidden="true" />
            <span>Certification:</span>
          </span>
          <span className="font-bold text-[#1E1B4B]">Verified Credential</span>
        </div>
      </div>

      {/* Primary Action Button */}
      <div className="space-y-3 mb-6">
        <Button
          variant="primary"
          size="lg"
          onClick={onOpenEnrollModal}
          className="w-full justify-center group text-base py-3.5 shadow-md shadow-indigo-600/10"
        >
          <span>Enroll in Next Cohort</span>
          <Sparkles className="w-4 h-4 ml-1.5 text-[#FBBF24]" aria-hidden="true" />
        </Button>

        <button
          type="button"
          onClick={handleDownloadSyllabus}
          className="w-full flex items-center justify-center gap-2 py-2.5 px-4 rounded-xl text-xs font-bold text-[#4338CA] bg-[#FAF8F5] hover:bg-[#EEF2FF] border border-[#E7E0D6] transition-colors focus-visible:outline-2 focus-visible:outline-[#4338CA] cursor-pointer"
        >
          <Download className="w-3.5 h-3.5" aria-hidden="true" />
          <span>Download Syllabus Overview (TXT)</span>
        </button>
      </div>

      {/* Course Inclusions Checklist */}
      <div className="space-y-3 pt-2">
        <p className="text-xs font-bold text-[#1E1B4B] uppercase tracking-wider">
          Included in this Cohort:
        </p>
        <ul className="space-y-2 text-xs text-[#475569]">
          {inclusions.map((item) => (
            <li key={item} className="flex items-start gap-2">
              <Check className="w-4 h-4 text-emerald-600 shrink-0 mt-0.5" aria-hidden="true" />
              <span>{item}</span>
            </li>
          ))}
        </ul>
      </div>

      {/* Reassurance Footer */}
      <div className="mt-6 pt-4 border-t border-[#E7E0D6] flex items-center gap-2 text-[11px] text-[#64748B]">
        <ShieldCheck className="w-4 h-4 text-emerald-600 shrink-0" aria-hidden="true" />
        <span>7-day satisfaction guarantee with refund option.</span>
      </div>
    </div>
  );
}
